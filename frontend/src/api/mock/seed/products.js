/** Tồn kho giả lập ổn định theo id (không random mỗi lần load). */
function stockFor(id, labels) {
  let seed = [...id].reduce((s, c) => s + c.charCodeAt(0), 0)
  return labels.map((label, i) => {
    seed = (seed * 9301 + 49297) % 233280
    const inStock = i < 3 ? seed % 7 !== 0 : seed % 4 !== 0
    return { label, inStock }
  })
}

